test('dev defaults include both testnets independently of the production preference', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('block.testnets', 'false'))
  await page.goto('/')
  const network = page.getByRole('combobox', { name: 'Transaction network' })
  await expect(network.locator('option')).toHaveCount(5)
  for (const [key, symbol] of [['sepolia', 'ETH'], ['amoy', 'POL']] as const) {
    await network.selectOption(key)
    await expect(page.getByRole('combobox', { name: 'Asset to send' })).toHaveValue(symbol)
    await expect(page.getByRole('button', { name: 'Token amount', exact: true })).toBeEnabled()
    await expect(page.locator('.mode-label')).toContainText('TESTNET')
    await page.getByRole('tab', { name: 'Swap' }).click()
    await expect(page.getByRole('button', { name: 'Connect wallet to swap' })).toBeDisabled()
    await page.getByRole('tab', { name: 'Send' }).click()
  }
  await page.getByRole('button', { name: 'Networks', exact: true }).click()
  await expect(page.locator('.network-card')).toHaveCount(5)
  await expect(page.getByRole('heading', { name: 'Sepolia', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Polygon Amoy', exact: true })).toBeVisible()
})

for (const width of [390, 768, 1024, 1440]) {
  test(`layout fits ${width}px viewport`, async ({ page }) => {
    await page.setViewportSize({ width, height: 844 })
    await page.goto('/')
    await expect(page.getByRole('heading', { name: 'Transact', exact: true })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width)
    await page.getByRole('tab', { name: 'Receive' }).click()
    await expect(page.getByRole('button', { name: 'Connect wallet to receive' })).toBeVisible()
    await page.screenshot({ path: `artifacts/workspace-${width}.png`, fullPage: true })
  })
}
