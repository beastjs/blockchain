import { expect, test } from './fixtures'

test('workspace controls work without a wallet', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Transact', exact: true })).toBeVisible()
  await expect(page.getByText('Demo portfolio balance')).toBeVisible()
  const chart = page.locator('.chart-line')
  const originalPath = await chart.getAttribute('d')
  await page.getByRole('button', { name: '1M', exact: true }).click()
  await expect(chart).not.toHaveAttribute('d', originalPath!)
  await page.getByRole('tab', { name: 'Receive' }).click()
  await expect(page.getByRole('heading', { name: 'Your next destination.' })).toBeVisible()
  await page.getByRole('tab', { name: 'Swap' }).click()
  await expect(page.getByRole('button', { name: 'Connect wallet to swap' })).toBeEnabled()
  await page.getByRole('combobox', { name: 'Transaction network' }).selectOption('bitcoin')
  await expect(page.getByRole('button', { name: 'Connect wallet to swap' })).toBeDisabled()
  await page.getByRole('tab', { name: 'Send' }).click()
  await expect(page.getByRole('combobox', { name: 'Asset to send' })).toHaveValue('BTC')
  await page.getByRole('button', { name: 'Preferences', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByRole('switch', { name: 'Hide balances' }).check()
  await page.getByRole('switch', { name: 'Show test networks' }).uncheck()
  await page.getByRole('button', { name: 'Done', exact: true }).click()
  await expect(page.locator('.portfolio-value h2')).toHaveText('••••••')
  await expect(page.getByRole('combobox', { name: 'Transaction network' }).locator('option')).toHaveCount(3)
  await page.getByRole('button', { name: 'Show balances' }).click()
  await page.getByRole('button', { name: 'View all' }).click()
  await expect(page.getByRole('heading', { name: 'Every move. On record.' })).toBeVisible()
  await page.getByRole('textbox', { name: 'Search transactions' }).fill('USDC')
  await expect(page.locator('.activity-row')).toHaveCount(1)
  await page.getByRole('button', { name: 'Pending', exact: true }).click()
  await expect(page.getByText('No transactions match this filter.')).toBeVisible()
  await page.getByRole('button', { name: 'Networks', exact: true }).click()
  await expect(page.locator('.network-card')).toHaveCount(3)
  await page.getByRole('button', { name: 'Transact', exact: true }).nth(2).click()
  await expect(page.getByRole('combobox', { name: 'Transaction network' })).toHaveValue('bitcoin')
  await expect(page.getByText('Demo portfolio balance')).toBeVisible()
  expect(errors).toEqual([])
})

